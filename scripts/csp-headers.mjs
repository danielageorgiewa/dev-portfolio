// Writes dist/_headers with the site's Content-Security-Policy.
//
// The policy allows scripts from this site only, plus the exact inline scripts that are in
// the built pages (Astro inlines small scripts, and a few components use `is:inline`). Their
// SHA-256 hashes are read from the build output, so the policy cannot drift from the pages.
// Runs at the end of every `astro build` (see astro.config.mjs). By hand:
//
//   node scripts/csp-headers.mjs [dist]            write dist/_headers
//   node scripts/csp-headers.mjs [dist] --print    print the policy and write nothing
//
// The other security headers are in netlify.toml. Netlify applies both files.

import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const MARK_START = '# csp:start (generated by scripts/csp-headers.mjs, do not edit)';
const MARK_END = '# csp:end';

async function htmlFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(path)));
    else if (entry.name.endsWith('.html')) out.push(path);
  }
  return out;
}

const SCRIPT = /<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi;
// Data blocks are not executed, so the policy does not apply to them.
const DATA_TYPE = /\btype\s*=\s*["']?(application\/(ld\+)?json|text\/plain)\b/i;

/** Hashes of every inline script in an HTML document, as CSP source expressions. */
export function inlineScriptHashes(html) {
  const hashes = [];
  for (const [, attrs, body] of html.matchAll(SCRIPT)) {
    if (/\bsrc\s*=/i.test(attrs) || DATA_TYPE.test(attrs) || body === '') continue;
    hashes.push(`'sha256-${createHash('sha256').update(body, 'utf8').digest('base64')}'`);
  }
  return hashes;
}

export function buildPolicy(scriptHashes) {
  return [
    "default-src 'self'",
    ["script-src 'self'", ...scriptHashes].join(' '),
    // Astro inlines small stylesheets and the pages carry style attributes.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    // Vite inlines the small arrow fonts as data: URIs.
    "font-src 'self' data:",
    "media-src 'self'",
    "connect-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    'upgrade-insecure-requests',
  ].join('; ');
}

export async function writeCspHeaders(distDir, { print = false } = {}) {
  const files = await htmlFiles(distDir);
  if (files.length === 0) throw new Error(`csp-headers: no HTML files in ${distDir}`);
  const hashes = new Set();
  let handlers = 0;
  for (const file of files) {
    const html = await readFile(file, 'utf8');
    for (const hash of inlineScriptHashes(html)) hashes.add(hash);
    // Inline event handlers (onclick="...") cannot be hashed and would be blocked.
    handlers += (html.replace(SCRIPT, '').match(/<[a-z][^>]*\son[a-z]+\s*=/gi) ?? []).length;
  }
  if (handlers > 0) {
    throw new Error(
      `csp-headers: ${handlers} inline event handler attribute(s) in the build. ` +
        'The policy blocks them: attach the listener from a script.',
    );
  }
  const policy = buildPolicy([...hashes].sort());
  if (print) return { policy, pages: files.length, scripts: hashes.size };

  const block = `${MARK_START}\n/*\n  Content-Security-Policy: ${policy}\n${MARK_END}\n`;
  const target = join(distDir, '_headers');
  // Keep anything that public/_headers contributed; replace only this script's block.
  let current = '';
  try {
    current = await readFile(target, 'utf8');
  } catch {
    // No _headers yet.
  }
  const start = current.indexOf(MARK_START);
  const end = current.indexOf(MARK_END);
  const rest = start !== -1 && end !== -1 ? current.slice(0, start) + current.slice(end + MARK_END.length + 1) : current;
  await writeFile(target, `${rest}${rest && !rest.endsWith('\n') ? '\n' : ''}${block}`);
  return { policy, pages: files.length, scripts: hashes.size };
}

/** Astro integration: write the header file once the pages exist. */
export function cspHeaders() {
  return {
    name: 'csp-headers',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const { pages, scripts } = await writeCspHeaders(fileURLToPath(dir));
        logger.info(`_headers written: ${scripts} inline script hash(es) from ${pages} page(s)`);
      },
    },
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const print = args.includes('--print');
  const dist = resolve(args.find((a) => !a.startsWith('--')) ?? 'dist');
  const { policy, pages, scripts } = await writeCspHeaders(dist, { print });
  console.log(print ? policy : `${join(dist, '_headers')}: ${scripts} inline script hash(es) from ${pages} page(s)`);
}
